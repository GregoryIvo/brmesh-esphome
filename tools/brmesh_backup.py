#!/usr/bin/env python3
"""Decode a BRmesh app backup and print the mesh key, devices, rooms and ready-to-paste ESPHome YAML.

The BRmesh Android app (Settings -> Backup / Export) writes a file named BRMESH_BACKUP<date>.json that is NOT
plain JSON: it is Base64 of AES-128-CBC (PKCS#7) with a fixed key and IV baked into the app. This script
undoes that so you can read your mesh key and short addresses without adb or a rooted phone.

Usage:
    python3 tools/brmesh_backup.py BRMESH_BACKUP2026.json            # human readable summary + YAML
    python3 tools/brmesh_backup.py BRMESH_BACKUP2026.json --json     # dump the decrypted JSON
    python3 tools/brmesh_backup.py BRMESH_BACKUP2026.json --yaml-only

Requires the `cryptography` package (pip install cryptography).
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import sys

APP_AES_KEY = b"brgdbrgdbrgdbrgd"
APP_AES_IV = b"0392039203920300"


def decrypt_backup(raw: bytes) -> dict:
    try:
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    except ImportError:  # pragma: no cover
        sys.exit("The 'cryptography' package is required: pip install cryptography")
    text = raw.decode("ascii", errors="ignore").strip()
    if text.startswith("{"):
        return json.loads(text)  # already decrypted
    blob = base64.b64decode(re.sub(r"\s+", "", text))
    decryptor = Cipher(algorithms.AES(APP_AES_KEY), modes.CBC(APP_AES_IV)).decryptor()
    padded = decryptor.update(blob) + decryptor.finalize()
    pad = padded[-1]
    if not 1 <= pad <= 16 or padded[-pad:] != bytes([pad]) * pad:
        sys.exit("Decryption produced invalid padding; is this really a BRmesh backup file?")
    return json.loads(padded[:-pad].decode("utf-8"))


def mesh_key_hex(ctrlkey: str) -> str:
    """The app stores the mesh key as a 4-character string; the bytes on air are its ASCII codes."""
    ctrlkey = (ctrlkey or "").strip()
    if len(ctrlkey) == 4:
        return ctrlkey.encode("ascii").hex()
    if re.fullmatch(r"[0-9a-fA-F]{8}", ctrlkey):
        return ctrlkey.lower()
    raise ValueError(f"Unexpected Ctrlkey format: {ctrlkey!r}")


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "group"


def build_yaml(key_hex: str, devices: list[dict], groups: list[dict]) -> str:
    lines = [
        "# Generated by tools/brmesh_backup.py from your BRmesh app backup.",
        "# Put the mesh key in secrets.yaml and keep it private: anyone with it can control your lights.",
        f"#   brmesh_mesh_key: \"{key_hex}\"",
        "",
        "light:",
    ]
    addresses = sorted({int(d["addr"]) for d in devices if int(d.get("addr", 0)) > 0})
    lines += [
        "  - platform: brmesh",
        "    brmesh_id: brmesh_hub",
        "    id: brmesh_all_lights",
        "    name: BRMesh All Lights",
        f"    addresses: [{', '.join(str(a) for a in addresses)}]",
    ]
    by_group: dict[int, list[int]] = {}
    for d in devices:
        if int(d.get("addr", 0)) > 0:
            by_group.setdefault(int(d.get("groupId", 0)), []).append(int(d["addr"]))
    names = {int(g.get("groupId", 0)): g.get("groupName", "") for g in groups}
    for gid, addrs in sorted(by_group.items()):
        gname = names.get(gid) or f"Group {gid}"
        if len(addrs) == len(addresses):
            continue  # identical to All Lights
        lines += [
            "",
            "  - platform: brmesh",
            "    brmesh_id: brmesh_hub",
            f"    id: brmesh_{slug(gname)}",
            f"    name: BRMesh {gname}",
            f"    addresses: [{', '.join(str(a) for a in sorted(addrs))}]",
        ]
    lines += ["", "  # Individual bulbs (optional; they share the mesh with the groups above):"]
    for d in sorted(devices, key=lambda x: int(x.get("addr", 0))):
        if int(d.get("addr", 0)) <= 0:
            continue
        lines += [
            f"  # - platform: brmesh",
            f"  #   brmesh_id: brmesh_hub",
            f"  #   name: {d.get('name') or 'Bulb ' + str(d['addr'])}",
            f"  #   address: {int(d['addr'])}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("backup", help="BRMESH_BACKUP*.json exported by the app")
    parser.add_argument("--json", action="store_true", help="print the decrypted JSON and exit")
    parser.add_argument("--yaml-only", action="store_true", help="print only the generated YAML")
    args = parser.parse_args()

    with open(args.backup, "rb") as handle:
        data = decrypt_backup(handle.read())
    if args.json:
        print(json.dumps(data, indent=2, ensure_ascii=False))
        return

    key_hex = mesh_key_hex(data.get("Ctrlkey", ""))
    devices = data.get("BleDv") or []
    groups = data.get("Group") or []
    yaml_text = build_yaml(key_hex, devices, groups)
    if args.yaml_only:
        print(yaml_text, end="")
        return

    print(f"Mesh key (Ctrlkey): {data.get('Ctrlkey')!r} -> brmesh_mesh_key: \"{key_hex}\"")
    print(f"Devices: {len(devices)}   Rooms/groups: {len(groups)}")
    print()
    print(f"{'addr':>4}  {'type':>5}  {'group':>5}  {'did':<12}  name")
    for d in sorted(devices, key=lambda x: int(x.get("addr", 0))):
        print(f"{int(d.get('addr', 0)):>4}  {int(d.get('type', 0)):>5}  {int(d.get('groupId', 0)):>5}  "
              f"{d.get('did', ''):<12}  {d.get('name', '')}")
    if groups:
        print()
        for g in groups:
            print(f"group {g.get('groupId')}: {g.get('groupName')}")
    print()
    print("---- ESPHome YAML ----")
    print(yaml_text, end="")


if __name__ == "__main__":
    main()
